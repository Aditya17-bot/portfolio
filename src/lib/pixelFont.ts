const SIZE = 28;
const ROWS = 5;
const LINE_GAP = 2;

function lineWidth(text: string) {
  return [...text].reduce((w, ch, i) => w + (GLYPHS[ch]?.[0].length ?? 3) + (i ? 1 : 0), 0);
}

/** Lines of text, centred on a 28x28 grid, as an MNIST-style input (1 = ink). */
export function textFrame(lines: string[]): Float32Array {
  const x = new Float32Array(SIZE * SIZE);
  const height = lines.length * ROWS + (lines.length - 1) * LINE_GAP;
  let top = Math.floor((SIZE - height) / 2);
  for (const line of lines) {
    const text = line.toUpperCase();
    let left = Math.floor((SIZE - lineWidth(text)) / 2);
    for (const ch of text) {
      const g = GLYPHS[ch] ?? GLYPHS[" "];
      for (let r = 0; r < ROWS; r++)
        for (let c = 0; c < g[r].length; c++)
          if (g[r][c] === "#" && top + r < SIZE && left + c < SIZE && left + c >= 0) x[(top + r) * SIZE + left + c] = 1;
      left += g[0].length + 1;
    }
    top += ROWS + LINE_GAP;
  }
  return x;
}
